"""Generate project Lua tooltips from proven PT reservoir rows (not original Lua)."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROJECT = ROOT / 'PhongThanSource'


def generate():
    effects = (PROJECT / 'Deploy/ProjectContent/settings/phongthan/ConsumableEffects.txt').read_text().splitlines()
    keys = {tuple(map(int, line.split('\t')[:2])) for line in effects[1:] if line.strip() and int(line.split('\t')[2]) <= 2}
    rows = {}
    for role in ('Server', 'Client'):
        source = ROOT / 'PhongThanRuntime-Loose' / role / 'settings/item/001/ibitem.txt'
        for line in source.read_bytes().splitlines()[1:]:
            c = line.split(b'\t')
            if len(c) < 70 or c[1] != b'8':
                continue
            key = int(c[2]), int(c[3])
            if key not in keys:
                continue
            assert c[12] == b'NONE'
            value = (int(c[9]), int(c[30]), int(c[31]))
            assert value[0] > 0 and value[1] in (153, 154) and value[2] > 0
            assert key not in rows or rows[key] == value, ('role mismatch', key)
            rows[key] = value
    assert set(rows) == keys
    # Four instant 3000-point drinks have UseCount=1; they are not reservoirs.
    instant = {key: value for key, value in rows.items() if value[0] == 1}
    rows = {key: value for key, value in rows.items() if value[0] > 1}
    folder = PROJECT / 'Deploy/ProjectContent/script/item/phongthan_reservoir'
    for detail, part in instant:
        stale = folder / f'pool_{detail}_{part}.lua'
        if stale.is_file():
            assert stale.resolve().parent == folder.resolve()
            assert stale.read_bytes().startswith(b'-- Project reconstruction from IBItem')
            stale.unlink()
    lines = ['#pragma once', '// Generated by Tools/build_reservoir_tooltips.py. Capacity remains in the',
             '// existing saved/synchronized field; a reservoir is ONE inventory object.',
             'inline const char* PhongThanReservoirTooltip(int genre,int detail,int part,int capacity,const char* script)',
             '{', '    if(genre!=8 || !script || strcmp(script,"NONE")) return 0;', '    switch(detail) {']
    manifest = []
    for (detail, part), (capacity, effect, rate) in sorted(rows.items()):
        path = f'script/item/phongthan_reservoir/pool_{detail}_{part}.lua'
        native = '\\' + path.replace('/', '\\')
        lines.append(f'    case {detail}: return part=={part} && capacity=={capacity} ? "{native.replace(chr(92), chr(92)*2)}" : 0;')
        # TCVN3 bytes match the client's established Vietnamese font encoding.
        label = b'Sinh l\xf9c' if effect == 153 else b'N\xe9i l\xf9c'
        payload = (f'-- Project reconstruction from IBItem detail={detail}, part={part}; original Lua unavailable.\n'
                   '-- Read-only snapshot supplied by CoreClient. No item use or mutation on hover.\n'
                   'function GetDesc(nRemaining)\n'
                   f'    if nRemaining < 0 then nRemaining = 0 end\n'
                   f'    if nRemaining > {capacity} then nRemaining = {capacity} end\n'
                   '    return "<color=0,255,0>').encode('ascii') + label + (
                   f' c\u00dfn l\u00b9i: <color=255,255,0>" .. format("%d", nRemaining) .. " / {capacity}<color><enter>'
                   f'H\u00e5i ph\u00f4c {rate} \u00aei\u00d3m / 0.5 gi\u00a9y.<enter>Nh\u00cap chu\u00e9t ph\u00b6i \u00ae\u00d3 b\u00cbt/t\u00bet b\u00d7nh.<color>"\nend\n').encode('latin1')
        target = PROJECT / 'Deploy/ProjectContent' / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload)
        manifest.append(dict(detail=detail, part=part, capacity=capacity, effect=effect, rate=rate,
                             path=path, sha256=hashlib.sha256(payload).hexdigest()))
    lines += ['    }', '    return 0;', '}', '']
    (PROJECT / 'Headers/PhongThanReservoirs.h').write_text('\n'.join(lines), encoding='ascii')
    (PROJECT / 'Deploy/ProjectContent/settings/phongthan/ReservoirTooltips.json').write_text(
        json.dumps(dict(classification='PROJECT_RECONSTRUCTION_FROM_PT_IBITEM', rows=manifest,
                        excluded_instant_drinks=[list(key) for key in instant]), indent=2)+'\n')
    print(f'Generated {len(rows)} reservoir Lua tooltips')


if __name__ == '__main__':
    generate()
