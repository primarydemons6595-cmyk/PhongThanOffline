inline unsigned int PhongThanCanonicalMapIdentityCount()
{
	return (unsigned int)(sizeof(g_PhongThanCanonicalMapIdentities) /
		sizeof(g_PhongThanCanonicalMapIdentities[0]));
}

inline const char* PhongThanMapEvidenceName(PHONGTHAN_MAP_MAPPING_EVIDENCE evidence)
{
	switch (evidence)
	{
	case PHONGTHAN_MAP_CONFIRMED_FROM_DATA: return "CONFIRMED_FROM_DATA";
	case PHONGTHAN_MAP_CONFIRMED_FROM_EXISTING_RUNTIME: return "CONFIRMED_FROM_EXISTING_RUNTIME";
	case PHONGTHAN_MAP_LEGACY_COMPATIBILITY: return "LEGACY_COMPATIBILITY";
	case PHONGTHAN_MAP_PROJECT_TERRITORY: return "PROJECT_TERRITORY";
	default: return "UNKNOWN";
	}
}

inline void PhongThanClearMapResolution(PHONGTHAN_MAP_RESOLUTION* result)
{
	if (!result) return;
	result->ContentMapId = 0;
	result->RuntimeMapId = 0;
	result->Evidence = PHONGTHAN_MAP_UNKNOWN;
}

inline bool PhongThanResolveContentMap(unsigned int contentMapId,
	PHONGTHAN_MAP_RESOLUTION* result)
{
	PhongThanClearMapResolution(result);
	for (unsigned int i = 0; i < PhongThanCanonicalMapIdentityCount(); ++i)
	{
		const PHONGTHAN_MAP_IDENTITY& entry = g_PhongThanCanonicalMapIdentities[i];
		if (entry.ContentMapId != contentMapId) continue;
		if (result)
		{
			result->ContentMapId = entry.ContentMapId;
			result->RuntimeMapId = entry.RuntimeMapId;
			result->Evidence = entry.Evidence;
		}
		return true;
	}
	return false;
}

// Reverse lookup is provided only for registered one-to-one rows.  It is used
// by the revivepos.ini boundary and never guesses by subtraction.
inline bool PhongThanResolveRuntimeMap(unsigned int runtimeMapId,
	PHONGTHAN_MAP_RESOLUTION* result)
{
	PhongThanClearMapResolution(result);
	for (unsigned int i = 0; i < PhongThanCanonicalMapIdentityCount(); ++i)
	{
		const PHONGTHAN_MAP_IDENTITY& entry = g_PhongThanCanonicalMapIdentities[i];
		if (entry.RuntimeMapId != runtimeMapId) continue;
		if (result)
		{
			result->ContentMapId = entry.ContentMapId;
			result->RuntimeMapId = entry.RuntimeMapId;
			result->Evidence = entry.Evidence;
		}
		return true;
	}
	return false;
}

